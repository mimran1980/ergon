#!/usr/bin/env python3
"""Write book/src/project/performance.md from the benchmark artifacts in this
repository, or with --check fail when the page differs from what they give.

No figure on the page is typed by hand. A table whose artifact is not in the
repository reads "not measured".

Inputs (paths relative to the repository root):

* Codec cost: ARTIFACTS/<suite>-<profile>/ for suite sbe or cluster and
  profile lto or no-lto, holding gate.txt (the gate's output) and the Criterion
  directory: either as `just bench` leaves a profile
  (target/bench-runs/<run>/<profile>/: gate.txt beside criterion/) or as
  `just bench-cluster` leaves one (target/criterion, gate.txt inside).
  Verdicts come from gate.txt (bench-cluster-report.py's parse_gate), means
  from the estimates. A gate.txt with no graded pair, or whose FAIL count
  does not match its final line, gives an "unreadable" row.
* Individual-message latency and failover: no artifact in this repository
  produces them, so their rows read "not measured".
* Host scheduling gaps: one gap-probe run of the shared-CPU lab
  (GAPS: <arm>-<rep>.summary.tsv, .hist.tsv, .irq.tsv, report.md), and the
  reviewed max causes in k8s/nri-shared-cpus/lab/results/max-causes.tsv.

Usage: generate-performance-page.py [--check] [--artifacts DIR] [--gaps DIR]
                                    [--causes FILE] [--out FILE]
"""
import argparse
import csv
import importlib.util
import json
import math
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = "https://github.com/mimran1980/ergon"
NOT = "not measured"
HEADER = (
    "<!-- Generated by scripts/generate-performance-page.py from benchmark artifacts."
    " Do not edit: run `just perf-page`. -->"
)

spec = importlib.util.spec_from_file_location("report", ROOT / "scripts" / "bench-cluster-report.py")
report = importlib.util.module_from_spec(spec)
spec.loader.exec_module(report)


def rel(path):
    path = pathlib.Path(path).resolve()
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return None


def link(text, path, kind="blob"):
    """A link to a repository path, or plain text for a path outside it."""
    where = rel(path)
    return text if where is None else f"[{text}]({REPO}/{kind}/main/{where})"


def ns(value):
    return f"{value:,}"


# ── Codec cost ─────────────────────────────────────────────────────────────

def gate_keys():
    """{gate label: (criterion group, ergon arm, per)}, from check-bench-gate.sh."""
    script = (ROOT / "scripts" / "check-bench-gate.sh").read_text()
    keys = {}
    for label, group, ergo, ref, _ceiling in re.findall(r'"([\w]+)\|([\w/]+)\|([\w-]+)\|([\w-]+)\|([\d.]+)"', script):
        keys[label] = (f"parity_{group.replace('/', '_')}", ergo, 1, ref)
    for group, ergo, ref, _ceiling in re.findall(r'"(cluster_\w+)\|([\w-]+)\|([\w-]+)\|([\d.]+)"', script):
        keys[group] = (group, ergo, report.BATCH, ref)
    return keys


def codec_rows(artifacts):
    rows, dist, provenance, keys = [], [], [], gate_keys()
    for suite in ("sbe", "cluster"):
        for profile in ("lto", "no-lto"):
            run = artifacts / f"{suite}-{profile}"
            gate = run / "gate.txt"
            if not gate.is_file():
                rows.append([f"{suite} codecs", profile, NOT, NOT, NOT, NOT])
                continue
            crit = run / "criterion" if (run / "criterion").is_dir() else run
            unit = "ns per op" if suite == "cluster" else "ns per iteration"
            text = gate.read_text()
            items = report.parse_gate(text)
            problem = report.gate_problem(text, items)
            if problem:
                rows.append([f"{suite} codecs", profile, NOT, NOT, NOT, f"gate output unreadable: {problem}"])
            for item in items:
                mean = NOT
                key = keys.get(item["name"])
                if key and (crit / key[0] / key[1] / "new" / "estimates.json").is_file():
                    stats = report.arm_stats(str(crit), key[0], key[1], key[2])
                    if stats["mean"] is not None:
                        mean = f"{stats['mean']:.3f} {unit}"
                ratio = item["ratio"] or NOT
                if item["ratio"] and item["ceiling"]:
                    ratio = f"{ratio} (ceiling {item['ceiling']})"
                if item["ci"]:
                    lo, hi = item["ci"]
                    spread = f"ratio CI {lo} to {hi} over {item['repeats']} invocation(s)"
                else:
                    spread = NOT
                verdict = f"{item['verdict']}: {item['note']}"
                rows.append([item["name"], profile, mean, ratio.replace("–", " to "), spread, verdict])
                if key:
                    dist += dist_rows(crit, item["name"], profile, key)
            manifest = crit / "run-manifest.json"
            facts = json.loads(manifest.read_text()) if manifest.is_file() else {}
            # `rustc` already reads "rustc 1.99.0 (...)", so it is printed as is.
            said = ", ".join(
                facts[key] if key == "rustc" else f"{key} {facts[key]}"
                for key in ("run_id", "commit", "rustc", "target", "host")
                if facts.get(key)
            )
            # Machine load around the run, as the runner's `uptime` lines gave it.
            for key, label in (("uptime_start", "load at start"), ("uptime_end", "load at end")):
                if facts.get(key):
                    said += f"; {label}: {facts[key].strip()}"
            provenance.append(
                f"- Codec cost, {suite} {profile}: {link('estimates and gate output', run, 'tree')}"
                f" ({said or 'no run-manifest.json'})."
            )
    if not provenance:
        provenance.append(
            "- Codec cost: no benchmark run is kept in this repository. `just bench` and"
            " `just bench-cluster` produce one; copy each profile (`target/bench-runs/<run>/<profile>`"
            " for SBE; `target/criterion` or `target/bench-no-lto/criterion`, with its `gate.txt`,"
            " for cluster) to `bench-results/<suite>-<profile>/` and run `just perf-page`."
        )
    return rows, dist, provenance


def dist_rows(crit, name, profile, key):
    """One row per arm of a graded pair: n, min, p50, p99, p99.99 and max of the
    per-sample times, pooled over every invocation (bench-cluster-report.py)."""
    group, ergo, per, ref = key
    out = []
    for arm in (ergo, ref):
        if not (crit / group / arm / "new" / "estimates.json").is_file():
            continue
        stats = report.arm_stats(str(crit), group, arm, per)
        cells = [ns(stats["n"])] + [
            report.cell(stats[q]) for q in ("min", "p50", "p99", "p9999", "max")
        ]
        out.append([name, profile, arm, *cells])
    return out


# ── Host scheduling gaps ───────────────────────────────────────────────────

def tsv(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def causes(path):
    out = {}
    if path.is_file():
        for line in path.read_text().splitlines():
            if line.startswith("#") or not line.strip():
                continue
            run, arm, cause, evidence = line.split("\t")
            out[(run, arm)] = (cause, evidence)
    return out


def overlapping(irq, start, end):
    """Interrupt counts in the sampler intervals that overlap [start, end]."""
    seen = {}
    for line in irq.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        lo, hi, delta, name = line.split("\t")
        if int(lo) <= end and int(hi) >= start:
            seen[name] = seen.get(name, 0) + int(delta)
    return ", ".join(f"{name} +{count}" for name, count in seen.items()) or "nothing counted"


def gap_rows(run, known):
    arms = {}
    for summary in sorted(run.glob("*.summary.tsv")):
        for row in tsv(summary):
            arms.setdefault(row["arm"], []).append((summary, row))
    rows = []
    for arm, reps in arms.items():
        hist, n, drops = {}, 0, 0
        for summary, row in reps:
            n += int(row["samples"])
            drops += int(row["dropped"])
            for bucket in tsv(summary.with_name(summary.name.replace(".summary.tsv", ".hist.tsv"))):
                upper = int(bucket["upper_ns"])
                hist[upper] = hist.get(upper, 0) + int(bucket["count"])
        buckets = sorted((upper, count) for upper, count in hist.items() if count)

        def pct(q):
            rank, seen = math.ceil(q * sum(c for _, c in buckets)), 0
            for upper, count in buckets:
                seen += count
                if seen >= rank:
                    return upper
            return buckets[-1][0]

        summary, top = max(reps, key=lambda rep: int(rep[1]["max_ns"]))
        end, gap = int(top["max_end_ns"]), int(top["max_ns"])
        irq = summary.with_name(summary.name.replace(".summary.tsv", ".irq.tsv"))
        seen = overlapping(irq, end - gap, end) if irq.is_file() else "no interrupt sampler"
        switches = int(top["nivcsw"])
        evidence = (
            f"rep {top['rep']}: {switches} involuntary {'switch' if switches == 1 else 'switches'} (rep total);"
            f" interrupts overlapping: {seen}"
        )
        cause, where = known.get((run.name, arm), ("unexplained", None))
        if where:
            path, _, anchor = where.partition("#")
            cause = f"[{cause}]({REPO}/blob/main/{path}{'#' + anchor if anchor else ''})"
        rows.append([
            arm, str(len(reps)), ns(n), f"≤ {ns(buckets[0][0])}", ns(pct(0.50)), ns(pct(0.99)),
            ns(pct(0.9999)), ns(gap), ns(drops), f"{cause} ({evidence})",
        ])
    return rows


def vm(run):
    page = run / "report.md"
    if page.is_file():
        m = re.search(r"^\| VM \| (.+?) \|$", page.read_text(), re.M)
        if m:
            return m.group(1)
    return "VM not recorded"


# ── Page ───────────────────────────────────────────────────────────────────

def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


def page(artifacts, gaps, causes_file):
    codec, dist, codec_prov = codec_rows(artifacts)
    gap = gap_rows(gaps, causes(causes_file)) if gaps.is_dir() else []
    # An arm run under ftrace pays the tracer's cost: it gets its own table.
    traced = [row for row in gap if "trace" in row[0]]
    gap = [row for row in gap if row not in traced] or [["host gaps", NOT] + [NOT] * 8]
    gap_head = ["arm", "reps", "n", "min", "p50", "p99", "p99.99", "max", "gap-log drops", "max cause"]
    traced_part = []
    if traced:
        names = ", ".join(row[0] for row in traced)
        traced_part = [
            "",
            f"Under ftrace ({names}): the tracer adds its own cost, so these are not"
            " comparable with the table above.",
            "",
            table(gap_head, traced),
        ]
    parts = [
        HEADER,
        "# Performance at a glance",
        "",
        "Every figure on this page is read from a benchmark artifact in this repository"
        " by `scripts/generate-performance-page.py`; a measurement with no artifact reads"
        " \"not measured\". Each table compares only runs of one workload and"
        " configuration. Raw runs and provenance are under [Provenance](#provenance).",
        "",
        "## Codec cost",
        "",
        "ergon against sbe-tool on equal work. The ratio is ergon / sbe-tool (the"
        " range over invocations when the run repeated); the verdict is the gate's"
        " (`scripts/check-bench-gate.sh`). INCONCLUSIVE passes the gate but is not"
        " parity: no winner is established. Method and ceilings:"
        " [Benchmarks](../sbe/benchmarks.md).",
        "",
        table(["workload", "lane", "mean cost", "ratio to sbe-tool", "uncertainty", "verdict"], codec),
        "",
        "### Codec cost distribution",
        "",
        "Per arm, runs of one profile pooled over every invocation. n is the number of"
        " Criterion samples; min, p50, p99, p99.99 and max are percentiles of the"
        " per-sample cost (ns per iteration for sbe codecs, ns per operation for cluster"
        " codecs). A sample is the mean of a batch of iterations, so these are not"
        " per-message tails: the max is the slowest sample's mean, and with n below 10,000"
        " p99.99 is that max. Each max is"
        " unexplained: the host was shared with other jobs while these ran, so a spike"
        " may be preemption or cache pollution; the next experiment is a rerun on an"
        " isolated CPU.",
        "",
        table(
            ["workload", "lane", "arm", "n", "min", "p50", "p99", "p99.99", "max"],
            dist or [[NOT, NOT, NOT] + [NOT] * 6],
        ),
        "",
        "## Individual-message latency",
        "",
        "One codec operation per sample, as the `latency_distribution` bench"
        " (`just bench-diagnostics`) times it. No run of it is kept here.",
        "",
        table(
            ["workload", "load", "n", "min", "p50", "p99", "p99.99", "max", "max cause", "throughput", "drops"],
            [["codec, one operation per sample", NOT] + [NOT] * 9],
        ),
        "",
        "Round trips between hosts, per transport: [Transport latency comparison](../transports/comparison.md)"
        " and [Latency findings at a glance](../findings.md).",
        "",
        "## Failover",
        "",
        table(
            ["scenario", "failure detection", "unavailable interval", "time to valid book"],
            [["cluster leader failover", NOT, NOT, NOT]],
        ),
        "",
        "The failover tests (`cluster-test-harness/tests/failover.rs` and"
        " `failover_own_driver.rs`) check that the client reconnects to the new leader"
        " within a deadline, not how long it takes.",
        "",
        "## Host scheduling gaps",
        "",
        "A busy-spin loop on an isolated CPU, with helper load on the pod's shared CPU:"
        " every loop iteration in ns, reps of one arm pooled. n is loop iterations;"
        " p50, p99 and p99.99 are histogram bucket upper bounds; min is the lowest"
        " bucket's bound; max is exact. Gap-log drops are gaps the probe could not log,"
        " not lost messages. Setup and fixes: [Shared CPUs](../deploy/shared-cpus.md).",
        "",
        table(gap_head, gap),
        *traced_part,
        "",
        "## Provenance",
        "",
        *codec_prov,
    ]
    if gaps.is_dir():
        parts.append(f"- Host scheduling gaps: {link(f'run {gaps.name}', gaps, 'tree')}, {vm(gaps)}.")
    parts.append(f"- Max causes: {link('max-causes.tsv', causes_file)}.")
    return "\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--artifacts", default=ROOT / "bench-results", type=pathlib.Path)
    parser.add_argument(
        "--gaps", default=ROOT / "k8s/nri-shared-cpus/lab/results/azure-20261024234841", type=pathlib.Path
    )
    parser.add_argument(
        "--causes", default=ROOT / "k8s/nri-shared-cpus/lab/results/max-causes.tsv", type=pathlib.Path
    )
    parser.add_argument("--out", default=ROOT / "book/src/project/performance.md", type=pathlib.Path)
    args = parser.parse_args()
    text = page(args.artifacts, args.gaps, args.causes)
    if args.check:
        if not args.out.is_file() or args.out.read_text() != text:
            print(f"FAIL: {args.out} is not what the artifacts give; run `just perf-page`", file=sys.stderr)
            return 1
        print(f"performance page: {args.out} matches its artifacts")
        return 0
    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
