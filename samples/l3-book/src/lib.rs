#[path = "generated/l3_codec.rs"]
mod l3_codec;
use l3_codec::Decimal as SbeDecimal;
pub use l3_codec::*;

/// One price level as callers supply it: `(price, size, orders)` where each
/// order is `(order_id, quantity)`. Levels are ragged — order counts differ
/// per level — which is why the staged `*_ragged` length builders exist.
pub type Level<'a> = (
    rust_decimal::Decimal,
    rust_decimal::Decimal,
    &'a [(u64, rust_decimal::Decimal)],
);

/// A side of the book: bids or asks, in price order.
pub type Side<'a> = [Level<'a>];

/// The `L3BookVarData` variant: orders carry a var-data `order_id` instead of
/// a fixed `u64`, so an order is `(quantity, order_id_bytes)`.
pub type VarDataLevel<'a> = (
    rust_decimal::Decimal,
    rust_decimal::Decimal,
    &'a [(rust_decimal::Decimal, &'a [u8])],
);

/// A side of an `L3BookVarData` book.
pub type VarDataSide<'a> = [VarDataLevel<'a>];

/// One `Depth3Test` level: `(name, items)` where each item is
/// `(value, tag_bytes)`. Three nesting levels including the var-data tag.
pub type Depth3Level<'a> = (u32, &'a [(u64, &'a [u8])]);

/// Exact header-inclusive encoded length of an L3 book for the given ragged
/// bids/asks + symbol, computed up-front via the staged `L3BookEncodedLength`.
/// Uses the schema-specific ragged builder wrappers — field-named methods,
/// zero user-defined constants.
// ANCHOR: book_encoded_length
pub fn book_encoded_length(
    bids: &Side<'_>,
    asks: &Side<'_>,
    symbol: &[u8],
) -> Result<usize, sbe_rt::EncodeError> {
    let after_bids = L3BookEncoder::compute_length().bids_ragged(bids.len() as u16, |g| {
        for (_, _, orders) in bids {
            g.add()?.orders(|og| {
                og.uniform(orders.len())?;
                Ok(())
            })?;
        }
        Ok(())
    })?;
    let after_asks = after_bids.asks_ragged(asks.len() as u16, |g| {
        for (_, _, orders) in asks {
            g.add()?.orders(|og| {
                og.uniform(orders.len())?;
                Ok(())
            })?;
        }
        Ok(())
    })?;
    let complete = after_asks.symbol(symbol.len())?;
    Ok(complete.encoded_length_with_header())
}
// ANCHOR_END: book_encoded_length

// ── L3BookVarData ────────────────────────────────────────────────────────
// VarData orders are ragged at two levels: each order carries a var-data
// `order_id` of differing length. Uses the staged builder with schema-specific
// ragged wrapper types (field-named `order_id(len)` methods, zero constants).

/// Exact header-inclusive encoded length of an L3BookVarData book, computed
/// via the staged `L3BookVarDataEncodedLength` builder (nested-ragged).
pub fn vardata_book_encoded_length(
    bids: &VarDataSide<'_>,
    asks: &VarDataSide<'_>,
    symbol: &[u8],
) -> Result<usize, sbe_rt::EncodeError> {
    let after_bids =
        L3BookVarDataEncoder::compute_length().bids_ragged(bids.len() as u16, |g| {
            for (_, _, orders) in bids {
                g.add()?.orders(|og| {
                    for (_, order_id) in *orders {
                        og.add()?.order_id(order_id.len())?;
                    }
                    Ok(())
                })?;
            }
            Ok(())
        })?;
    let after_asks = after_bids.asks_ragged(asks.len() as u16, |g| {
        for (_, _, orders) in asks {
            g.add()?.orders(|og| {
                for (_, order_id) in *orders {
                    og.add()?.order_id(order_id.len())?;
                }
                Ok(())
            })?;
        }
        Ok(())
    })?;
    let complete = after_asks.symbol(symbol.len())?;
    Ok(complete.encoded_length_with_header())
}

/// Encode an L3 order book into `buf`. Returns the header-inclusive encoded length.
///
/// Uses known-size group construction — counts are known from slice lengths,
/// so no back-patching is needed. All numeric fields use `rust_decimal::Decimal`
/// and the timestamp uses `chrono::DateTime<Utc>` via the concrete converter
/// accessors generated by the `with_domain_type` configuration.
// ANCHOR: encode_book
pub fn encode_book(
    buf: &mut [u8],
    bids: &Side<'_>,
    asks: &Side<'_>,
    symbol: &[u8],
) -> Result<usize, sbe_rt::EncodeError> {
    let complete = L3BookEncoder::try_wrap_and_apply_header(buf, 0)?
        .fixed(&L3BookFixedFields {
            exchange_timestamp: 1_720_000_000_000_000_000u64,
            sequence: 42,
            is_active: true.into(),
        })
        .bids(bids.len() as u16, |g| {
            for (price, size, orders) in bids {
                g.add(|mut e| {
                    e.try_price(*price).map_err(|_| {
                        sbe_rt::EncodeError::DomainConversionFailed {
                            field: "price",
                            reason: "conversion",
                        }
                    })?;
                    e.try_size(*size)
                        .map_err(|_| sbe_rt::EncodeError::DomainConversionFailed {
                            field: "size",
                            reason: "conversion",
                        })?;
                    e.orders(orders.len() as u16, |og| {
                        for (oid, qty) in *orders {
                            let raw_qty =
                                SbeDecimal::new(qty.mantissa() as i64, -(qty.scale() as i8));
                            og.add_struct(&L3BookBidsOrdersEntry {
                                order_id: *oid,
                                quantity: raw_qty,
                            })?;
                        }
                        Ok(())
                    })
                })?;
            }
            Ok(())
        })?
        .asks(asks.len() as u16, |g| {
            for (price, size, orders) in asks {
                g.add(|mut e| {
                    e.try_price(*price).map_err(|_| {
                        sbe_rt::EncodeError::DomainConversionFailed {
                            field: "price",
                            reason: "conversion",
                        }
                    })?;
                    e.try_size(*size)
                        .map_err(|_| sbe_rt::EncodeError::DomainConversionFailed {
                            field: "size",
                            reason: "conversion",
                        })?;
                    e.orders(orders.len() as u16, |og| {
                        for (oid, qty) in *orders {
                            let raw_qty =
                                SbeDecimal::new(qty.mantissa() as i64, -(qty.scale() as i8));
                            og.add_struct(&L3BookAsksOrdersEntry {
                                order_id: *oid,
                                quantity: raw_qty,
                            })?;
                        }
                        Ok(())
                    })
                })?;
            }
            Ok(())
        })?
        .symbol(symbol)?;
    Ok(complete.encoded_length_with_header())
}
// ANCHOR_END: encode_book

